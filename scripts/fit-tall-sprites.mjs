'use strict';

// dev-only, rerun when app/styles/pokesprite.scss changes: an unsealed tile shows its sprite at 1.3x in 49px between
// the name and the number, which the tallest sprites (a gigantamax, Sirfetch'd's leek) overrun, covering both. This
// writes app/styles/pokesprite-fit.scss, zooming each of those down to the space instead

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// keep in sync with .set-captured .icon-wrapper in styles/tracker.scss
const SPACE = 49;
const ZOOM = 1.3;

const STYLES = join(dirname(fileURLToPath(import.meta.url)), '..', 'app', 'styles');

const sheet = await readFile(join(STYLES, 'pokesprite.scss'), 'utf8');
const byHeight = new Map();
for (const [, selector, height] of sheet.matchAll(/^(\.pkicon[^{]+)\{ width: \d+px; height: (\d+)px;/gm)) {
  const h = Number(height);
  if (h * ZOOM > SPACE) {
    byHeight.set(h, [...(byHeight.get(h) ?? []), selector.trim()]);
  }
}

const rules = [...byHeight].sort((a, b) => a[0] - b[0]).map(([height, selectors]) => [
  `// ${height}px tall`,
  '.pokemon:not(.sealed) .set-captured .icon-wrapper :is(',
  selectors.map((selector) => `  ${selector}`).join(',\n'),
  ') {',
  `  zoom: ${Math.floor((SPACE / height) * 1000) / 1000};`,
  '}',
].join('\n'));

const out = [
  '// generated by scripts/fit-tall-sprites.mjs from pokesprite.scss: each sprite too tall for an unsealed tile\'s icon',
  '// space at its zoom, zoomed down to fit it; a sealed tile\'s larger sprite overlaps its lines by design, over a halo',
  '',
  rules.join('\n\n'),
  '',
].join('\n');

await writeFile(join(STYLES, 'pokesprite-fit.scss'), out);
console.log(`${[...byHeight.values()].flat().length} sprites in ${byHeight.size} heights`);
