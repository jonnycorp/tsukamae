'use strict';

// dev-only: a theme's own sprites, drawn from pokesprite's sheet by a recipe of the theme's (Game Boy's four greens,
// Riso's two inks), into public/themes/<slug>/; styles/theme-sprites.scss swaps them in. The balls and marks keep their
// own colours, which tell them apart. Run again after the sheet is updated (yarn sprites:themes)

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { toLch, toRgb } from '../app/palette/color.ts';
import { decode, encode } from './png.mjs';

const PUBLIC = join(dirname(fileURLToPath(import.meta.url)), '..', 'public');

// ---- recipes: each pixel's colour from its own, alpha kept

const bytes = (lch) => {
  const { r, g, b } = toRgb(lch);
  return [r, g, b].map((v) => Math.round(v * 255));
};

// Game Boy: the four greens of a pocket screen, picked by how light the pixel is. The palest sits above the tiles' own
// green and the deepest at the ink's, so a sprite still reads on a tile (keep in sync with Game Boy's seed in
// palette/themes.ts)
const POCKET = [
  { l: 0.25, c: 0.055, h: 140 },
  { l: 0.44, c: 0.09, h: 134 },
  { l: 0.63, c: 0.13, h: 126 },
  { l: 0.93, c: 0.09, h: 118 },
].map(bytes);
const POCKET_STEPS = [0.36, 0.53, 0.7];

function gameBoy (r, g, b) {
  const { l } = toLch({ r: r / 255, g: g / 255, b: b / 255, a: 1 });
  const step = POCKET_STEPS.filter((edge) => l >= edge).length;
  return POCKET[step];
}

// Riso: two inks laid on the white of the sprite, the blue in its shadows and the fluorescent pink through its
// mid-tones, each at a riso's three densities (none, a half-tone, solid); where both land they overprint purple (keep
// in sync with Riso's seed in palette/themes.ts)
const BLUE_INK = bytes({ l: 0.5, c: 0.16, h: 248 }).map((v) => v / 255);
const PINK_INK = bytes({ l: 0.68, c: 0.24, h: 352 }).map((v) => v / 255);
const density = (v) => (v < 0.25 ? 0 : v < 0.7 ? 0.55 : 1);
const clamp = (v) => Math.min(1, Math.max(0, v));

function riso (r, g, b) {
  const { l } = toLch({ r: r / 255, g: g / 255, b: b / 255, a: 1 });
  const blue = density(clamp((0.62 - l) / 0.42));
  const pink = density(clamp((0.95 - l) / 0.5));
  return [0, 1, 2].map((i) => Math.round(255 * (1 - blue * (1 - BLUE_INK[i])) * (1 - pink * (1 - PINK_INK[i]))));
}

const RECIPES = { 'game-boy': gameBoy, riso };

// ---- the images each theme redraws

function redraw (image, recipe) {
  const cache = new Map();
  const { pixels } = image;
  for (let o = 0; o < pixels.length; o += 4) {
    if (pixels[o + 3] === 0) {
      continue;
    }
    const key = (pixels[o] << 16) | (pixels[o + 1] << 8) | pixels[o + 2];
    let colour = cache.get(key);
    if (!colour) {
      colour = recipe(pixels[o], pixels[o + 1], pixels[o + 2]);
      cache.set(key, colour);
    }
    [pixels[o], pixels[o + 1], pixels[o + 2]] = colour;
  }
  return image;
}

const SHEET = 'pokesprite-v12.png';

// the styles that swap each theme's sheet in, behind every sprite
const swaps = ['// generated by scripts/theme-sprites.mjs (yarn sprites:themes): each theme\'s own sprites in place of the originals'];
for (const [slug, recipe] of Object.entries(RECIPES)) {
  const image = decode(join(PUBLIC, SHEET));
  if (!image) {
    throw new Error(`${SHEET}: not 8-bit RGBA or grey and alpha, or interlaced`);
  }
  const target = join(PUBLIC, 'themes', slug, SHEET);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, encode(redraw(image, recipe)));
  swaps.push(`:root[data-theme='${slug}'] .pkicon {`, `  background-image: url('/themes/${slug}/${SHEET}');`, '}', '');
  console.log(`${slug}: public/themes/${slug}/${SHEET}`);
}
writeFileSync(join(PUBLIC, '..', 'app', 'styles', 'theme-sprites.scss'), swaps.join('\n'));
